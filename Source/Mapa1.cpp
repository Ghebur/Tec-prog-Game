void Mapa1::desenhar(sf::RenderWindow& window) {
    for (int i = 0; i < LINHAS; i++) {
        for (int j = 0; j < COLUNAS; j++) {
            if (grade[i][j] == 1) {
                chao.setFillColor(sf::Color(34, 139, 34));
                chao.setPosition({j * larguraBloco, i * alturaBloco});
                window.draw(chao);
            } else if (grade[i][j] == 2) {
                chao.setFillColor(sf::Color(80, 50, 0));
                chao.setPosition({j * larguraBloco, i * alturaBloco});
                window.draw(chao);
            }
        }
    }
}

int Mapa1::getTile(sf::Vector2f pos) {
    int col = (int)(pos.x / larguraBloco);
    int lin = (int)(pos.y / alturaBloco);
    if (lin < 0 || lin >= LINHAS || col < 0 || col >= COLUNAS) return 0;
    return grade[lin][col];
}