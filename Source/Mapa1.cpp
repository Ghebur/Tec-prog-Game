void Mapa1::desenhar(sf::RenderWindow& window) {
    for (int i = 0; i < LINHAS; i++) {
        for (int j = 0; j < COLUNAS; j++) {
            if (grade[i][j] == 1 || grade[i][j] == 6) {
                chao.setFillColor(sf::Color(34, 139, 34));
                chao.setPosition({j * larguraBloco, i * alturaBloco});
                window.draw(chao);
            } else if (grade[i][j] == 2) {
                chao.setFillColor(sf::Color(80, 50, 0));
                chao.setPosition({j * larguraBloco, i * alturaBloco});
                window.draw(chao);
            }
        }
    }

    for (auto& plat : plataformas)
        plat.desenhar(window);
}

int Mapa1::getTile(sf::Vector2f pos) {
    int col = (int)(pos.x / larguraBloco);
    int lin = (int)(pos.y / alturaBloco);
    if (lin < 0 || lin >= LINHAS || col < 0 || col >= COLUNAS) return 0;
    return grade[lin][col];
}

std::vector<sf::Vector2f> Mapa1::getSpawnPoints(int tile) {
    std::vector<sf::Vector2f> pontos;
    for (int i = 0; i < LINHAS; i++)
        for (int j = 0; j < COLUNAS; j++)
            if (grade[i][j] == tile)
                pontos.push_back({j * larguraBloco, i * alturaBloco});
    return pontos;
}

void Mapa1::adicionarPlataforma(float x, float y) {
    plataformas.emplace_back(x, y);
}

void Mapa1::colidirComPersonagens(Personagens& p) {
    for (auto& plat : plataformas)
        plat.obstaculizar(p);
}
